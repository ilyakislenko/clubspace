// What the «?» button in the shell header tells about the page it is on: what
// the section is for, the real controls on it, and the video guides that show
// it. Patterns are relative to /workspace/<id>/ or /org/<id>/ ("" = the
// landing page); "*" stands for one id segment (a member, a group, a course).
// A page with no entry gets no button. Legacy routes that only redirect have
// none: the page they land on answers.

export const GUIDE_IDS = [
  "owner-setup",
  "invite",
  "attendance",
  "video-course",
  "money",
  "student",
  "federation",
] as const

export type GuideId = (typeof GUIDE_IDS)[number]

export const isGuideId = (value: unknown): value is GuideId =>
  typeof value === "string" && (GUIDE_IDS as readonly string[]).includes(value)


// What the «?» button in the shell header tells about the page it is on: what
// the section is for, the real controls on it, and the video guides that show
// it. Patterns are relative to /workspace/<id>/ or /org/<id>/ ("" = the
// landing page); "*" stands for one id segment (a member, a group, a course).
// A page with no entry gets no button. Legacy routes that only redirect have
// none: the page they land on answers.

export const GUIDE_IDS = [
  "owner-setup",
  "invite",
  "attendance",
  "video-course",
  "money",
  "student",
  "federation",
] as const

export type GuideId = (typeof GUIDE_IDS)[number]

export const isGuideId = (value: unknown): value is GuideId =>
  typeof value === "string" && (GUIDE_IDS as readonly string[]).includes(value)

// Who gets a control the page shows only to some of its viewers: a club
// access level (the sidebar's `access`) or the federation's admins.
export type HelpAccess = Access | "orgAdmin"

// A plain string: every viewer of the page has the control. Tagged: only
// viewers with that access (the page's own gating) see the line.
export type HelpAction = string | { text: string; access: HelpAccess }

export type HelpEntry = {
  title: string
  // One or two sentences: what the section is for and what it shows.
  purpose: string
  // 1–5 short imperative lines naming the controls on the page.
  actions: HelpAction[]
  guides?: GuideId[]
}

export type HelpArea = "workspace" | "org"

// The lines this viewer can act on.
export const visibleActions = (
  entry: HelpEntry,
  allows: (access: HelpAccess) => boolean,
): string[] =>
  entry.actions.flatMap((action) =>
    typeof action === "string" ? [action] : allows(action.access) ? [action.text] : [],
  )


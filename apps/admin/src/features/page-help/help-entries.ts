export type HelpRoute = { area: HelpArea; pattern: string }

// The registered pattern a pathname falls under: same number of segments,
// each equal or a "*"; the one with the fewest "*" wins, so users/requests
// beats users/*. null outside a club or a federation, or on a page with no
// entry.
export const matchHelpRoute = (
  pathname: string | null | undefined,
  patterns: { workspace: readonly string[]; org: readonly string[] },
): HelpRoute | null => {
  const [root, id, ...rest] = (pathname ?? "").split("/").filter(Boolean)
  if (!id || (root !== "workspace" && root !== "org")) return null
  const area: HelpArea = root
  let best: { pattern: string; wildcards: number } | null = null
  for (const pattern of patterns[area]) {
    const parts = pattern.split("/").filter(Boolean)
    if (parts.length !== rest.length) continue
    if (!parts.every((part, i) => part === "*" || part === rest[i])) continue
    const wildcards = parts.filter((part) => part === "*").length
    if (!best || wildcards < best.wildcards) best = { pattern, wildcards }
  }
  return best ? { area, pattern: best.pattern } : null
}

export const helpEntryFor = (
  pathname: string | null | undefined,
  vocabulary: ClubVocabulary,
): HelpEntry | null => {
  const registries = { workspace: workspaceHelp(vocabulary), org: orgHelp() }
  const route = matchHelpRoute(pathname, {
    workspace: Object.keys(registries.workspace),
    org: Object.keys(registries.org),
  })
  return route ? registries[route.area][route.pattern] : null
}
